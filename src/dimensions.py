# 사례 유형 균형. 판단 경계 축과 별개의 축이다.
#
# 두 축을 함께 관리하는 이유:
#   판단 경계 축(dimension)은 "약관의 어느 지점을 건드렸는가"이고
#   사례 유형(case type)은 "그 지점에서 어떤 성격의 사례인가"이다.
#   축이 고루 덮여도 전부 경계사례면 테스트 세트로 쓸 수 없다.
