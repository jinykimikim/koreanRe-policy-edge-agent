def type_gap(cases):
    """유형별 부족분을 돌려준다. {유형: 부족 건수}"""
    have = {}
    for c in cases:
        t = c.get("case_type")
        have[t] = have.get(t, 0) + 1
    gap = {}
    for t, target in CASE_TYPE_TARGET.items():
        short = target - have.get(t, 0)
        if short > 0:
            gap[t] = short
    return gap, have


def describe_types(gap):
    return "\n".join(
        f"- {t} {n}건: {CASE_TYPE_DESC[t]}" for t, n in gap.items())


def active_dimensions(clause_ids):
    """실제 조항에 연결되는 차원만 남긴다.

    약관이 바뀌면 의미 없어지는 차원이 생긴다. 그때 조용히 넘어가지 않고
    제외 사실을 드러내기 위해 (유효 목록, 제외 목록)을 함께 돌려준다.
    """
    ids = set(clause_ids)
    active, dropped = [], []
    for d in DIMENSIONS:
        hit = [a for a in d["anchors"] if a in ids]
        if hit:
            active.append(dict(d, matched_anchors=hit))
        else:
            dropped.append(d["name"])
    return active, dropped


def describe(dims):
    return "\n".join(
        f"- {d['name']}: {d['desc']}\n"
        f"  (관련 조항 예: {', '.join(d['matched_anchors'][:3])})"
        for d in dims)
